"""Normalize Reader data and write the JSONL and Markdown corpus."""

from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
import unicodedata
import warnings
from collections import defaultdict
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass
from hashlib import sha256
from pathlib import Path
from typing import Any, Protocol

JsonObject = dict[str, Any]
SCHEMA_VERSION = 2
EXCLUDED_DOCUMENT_TAG = "backfill"
GENERATED_NOTICE = "<!-- Generated by readwise-base. Manual changes will be replaced. -->"
MAX_FILENAME_BYTES = 240
WINDOWS_RESERVED_NAMES = {"con", "prn", "aux", "nul", "clock$"} | {
    f"{prefix}{number}" for prefix in ("com", "lpt") for number in range(1, 10)
}


class ReaderSource(Protocol):
    """Data required to build a complete corpus snapshot."""

    def list_records(self, *, category: str | None = None, include_content: bool = False) -> list[JsonObject]: ...

    def get_document_details(self, document_id: str) -> JsonObject: ...


@dataclass(frozen=True)
class BuildResult:
    documents: int
    documents_without_content: int
    documents_with_interactions: int
    documents_without_interactions: int
    highlights: int
    omitted_highlights: int
    excluded_backfill: int
    jsonl_path: Path
    markdown_dirs: tuple[Path, ...]


@dataclass(frozen=True)
class _CorpusLayout:
    jsonl_name: str
    markdown_directories: tuple[str, ...]
    preserve_unmanaged_files: bool
    obsolete_directories: tuple[str, ...] = ()


WITH_INTERACTIONS_DIRECTORY = "with-interactions"
WITHOUT_INTERACTIONS_DIRECTORY = "without-interactions"
MAIN_LAYOUT = _CorpusLayout(
    jsonl_name="corpus.jsonl",
    markdown_directories=(WITH_INTERACTIONS_DIRECTORY, WITHOUT_INTERACTIONS_DIRECTORY),
    preserve_unmanaged_files=True,
    obsolete_directories=("documents",),
)
BACKFILL_LAYOUT = _CorpusLayout(
    jsonl_name="backfill.jsonl",
    markdown_directories=("backfill",),
    preserve_unmanaged_files=False,
)


def _tags(value: Any) -> list[str]:
    if value is None:
        return []
    if isinstance(value, dict):
        return sorted(str(tag) for tag in value)
    if isinstance(value, list):
        if not all(isinstance(tag, str) for tag in value):
            raise ValueError("tags must contain only text values")
        return sorted(value)
    raise ValueError("tags must be an object or list")


def _is_backfill(tag: str) -> bool:
    return tag.strip().casefold().lstrip(".") == EXCLUDED_DOCUMENT_TAG


def _text(value: Any) -> str | None:
    if value is None:
        return None
    rendered = str(value).strip()
    return rendered or None


def _latest_note(notes: list[JsonObject]) -> str | None:
    populated = [note for note in notes if _text(note.get("content"))]
    if not populated:
        return None
    latest = max(populated, key=lambda note: (str(note.get("updated_at") or ""), str(note.get("id") or "")))
    return _text(latest.get("content"))


def _truncate_utf8(value: str, max_bytes: int) -> str:
    if len(value.encode("utf-8")) <= max_bytes:
        return value
    return value.encode("utf-8")[:max_bytes].decode("utf-8", errors="ignore").rstrip(" .")


def _safe_filename(title: str, *, max_bytes: int = MAX_FILENAME_BYTES - len(".md")) -> str:
    name = unicodedata.normalize("NFC", title)
    name = re.sub(r"[\x00-\x1f\x7f]", " ", name)
    name = name.replace("<", "‹").replace(">", "›")
    name = re.sub(r'[*?"]', "", name)
    name = re.sub(r"^[\s\\/:|]+|[\s\\/:|]+$", "", name)
    name = re.sub(r"\s*[\\/:|](?:\s*[\\/:|])*\s*", " - ", name)
    name = re.sub(r"\s+", " ", name).strip(" .")
    if not name:
        name = "Untitled"
    if name.split(".", maxsplit=1)[0].casefold() in WINDOWS_RESERVED_NAMES:
        name = f"_{name}"
    return _truncate_utf8(name, max_bytes) or "Untitled"


def _filename(stem: str, suffix: str | None = None) -> str:
    postfix = f" — {suffix}" if suffix else ""
    extension = ".md"
    available = MAX_FILENAME_BYTES - len((postfix + extension).encode("utf-8"))
    fitted_stem = _truncate_utf8(stem, available) or "Untitled"
    return f"{fitted_stem}{postfix}{extension}"


def _id_suffixes(document_id: str) -> list[str]:
    readable = re.sub(r"[^A-Za-z0-9_-]", "", document_id)
    if readable:
        start = min(8, len(readable))
        suffixes = [readable[:length] for length in range(start, len(readable) + 1)]
    else:
        suffixes = []
    digest = sha256(document_id.encode("utf-8")).hexdigest()
    suffixes.extend(f"{readable[:8]}-{digest[:length]}".lstrip("-") for length in range(8, 17))
    return suffixes


def _quote_yaml(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _blockquote(text: str) -> str:
    return "\n".join(f"> {line}" if line else ">" for line in text.splitlines())


def _markdown(record: JsonObject) -> str:
    frontmatter_fields = {
        "schema_version": record["schema_version"],
        "reader_id": record["id"],
        "title": record["title"],
        "author": record["author"],
        "source_url": record["source_url"],
        "reader_url": record["reader_url"],
        "category": record["category"],
        "location": record["location"],
        "document_tags": record["document_tags"],
        "published_date": record["published_date"],
        "saved_at": record["saved_at"],
        "updated_at": record["updated_at"],
        "first_opened_at": record["first_opened_at"],
        "last_opened_at": record["last_opened_at"],
        "highlight_count": len(record["highlights"]),
    }
    lines = ["---"]
    lines.extend(f"{key}: {_quote_yaml(value)}" for key, value in frontmatter_fields.items() if value is not None)
    lines.extend(["---", "", GENERATED_NOTICE, "", f"# {record['title']}"])

    summary = record.get("summary")
    if summary:
        lines.extend(["", "## Summary", "", summary])

    document_note = record.get("document_note")
    if document_note:
        lines.extend(["", "## Document note", "", document_note])

    highlights = record["highlights"]
    if highlights:
        lines.extend(["", "## Highlights"])
        for index, highlight in enumerate(highlights, start=1):
            lines.extend(
                [
                    "",
                    f"### Highlight {index}",
                    "",
                    f"<!-- reader-highlight-id: {highlight['id']} -->",
                    "",
                    _blockquote(highlight["text"]),
                ]
            )
            if highlight.get("note"):
                lines.extend(["", "Note:", "", highlight["note"]])
            if highlight.get("tags"):
                lines.extend(["", f"Tags: {', '.join(highlight['tags'])}"])
            if highlight.get("reader_url"):
                lines.extend(["", f"[Open highlight in Reader]({highlight['reader_url']})"])

    lines.extend(["", "## Full article", "", record["content"]["text"] or "(No content available.)"])
    return "\n".join(lines).rstrip() + "\n"


def _write_text_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.replace(temporary_name, path)
    except BaseException:
        Path(temporary_name).unlink(missing_ok=True)
        raise


def _previous_records(jsonl_path: Path) -> dict[str, JsonObject]:
    if not jsonl_path.exists():
        return {}
    records: dict[str, JsonObject] = {}
    for line in jsonl_path.read_text(encoding="utf-8").split("\n"):
        if not line.strip():
            continue
        row = json.loads(line)
        record_id = row.get("id")
        if isinstance(record_id, str):
            records[record_id] = row
    return records


def _assign_markdown_paths(
    records: list[JsonObject],
    destination: Path,
    previous_records: dict[str, JsonObject],
    markdown_directory: str,
    *,
    preserve_unmanaged_files: bool = True,
) -> None:
    documents_dir = destination / markdown_directory
    managed_filenames = {
        path.name
        for record in previous_records.values()
        if isinstance((value := record.get("markdown_path")), str)
        and (path := Path(value)).parent == Path(markdown_directory)
    }
    existing_entries = list(documents_dir.iterdir()) if documents_dir.is_dir() else []
    used = (
        {path.name.casefold() for path in existing_entries if path.name not in managed_filenames}
        if preserve_unmanaged_files
        else set()
    )
    assigned: set[str] = set()
    retained_ids: set[str] = set()

    for record in records:
        document_id = str(record["id"])
        stem = _safe_filename(record["title"])
        previous = previous_records.get(document_id)
        previous_title = previous.get("title") if previous else None
        previous_path = previous.get("markdown_path") if previous else None
        if not isinstance(previous_title, str) or not isinstance(previous_path, str):
            continue
        relative_path = Path(previous_path)
        if relative_path.parent != Path(markdown_directory) or _safe_filename(previous_title) != stem:
            continue
        key = relative_path.name.casefold()
        if key in assigned:
            continue
        record["markdown_path"] = relative_path.as_posix()
        retained_ids.add(document_id)
        assigned.add(key)
        used.add(key)

    for record in records:
        document_id = str(record["id"])
        if document_id in retained_ids:
            continue
        stem = _safe_filename(record["title"])
        filename = _filename(stem)
        if filename.casefold() in used:
            for suffix in _id_suffixes(document_id):
                filename = _filename(stem, suffix)
                if filename.casefold() not in used:
                    break
            else:  # pragma: no cover - SHA-256 prefixes make this unreachable for unique IDs.
                raise ValueError(f"could not assign a unique filename for document {record['id']}")
        used.add(filename.casefold())
        record["markdown_path"] = f"{markdown_directory}/{filename}"


def _validate_unique_ids(records: list[JsonObject], kind: str) -> None:
    seen: set[str] = set()
    for record in records:
        value = record.get("id")
        if value is None or not str(value).strip():
            raise ValueError(f"{kind} is missing an id")
        record_id = str(value)
        if record_id in seen:
            raise ValueError(f"duplicate {kind} id: {record_id}")
        seen.add(record_id)


def _copy_unmanaged_entries(
    source_directory: Path,
    target_directory: Path,
    previous_records: dict[str, JsonObject],
    markdown_directory: str,
) -> None:
    if not source_directory.is_dir():
        return
    managed_filenames = {
        path.name
        for record in previous_records.values()
        if isinstance((value := record.get("markdown_path")), str)
        and (path := Path(value)).parent == Path(markdown_directory)
    }
    for source in source_directory.iterdir():
        if source.name in managed_filenames:
            continue
        target = target_directory / source.name
        if source.is_symlink():
            target.symlink_to(os.readlink(source))
        elif source.is_dir():
            shutil.copytree(source, target, symlinks=True)
        else:
            shutil.copy2(source, target)


def _remove_path(path: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink(missing_ok=True)
    elif path.exists():
        shutil.rmtree(path)


def _publication_names(layout: _CorpusLayout) -> tuple[str, ...]:
    return (layout.jsonl_name, *layout.markdown_directories, *layout.obsolete_directories)


def _generated_names(layout: _CorpusLayout) -> tuple[str, ...]:
    return (layout.jsonl_name, *layout.markdown_directories)


def _restore_backup(backup: Path, destination: Path, layout: _CorpusLayout) -> None:
    manifest = json.loads((backup / "transaction.json").read_text(encoding="utf-8"))
    had_paths = manifest.get("had_paths")
    if not isinstance(had_paths, dict):
        raise ValueError(f"invalid publication manifest at {backup}")

    for name in _publication_names(layout):
        live_path = destination / name
        backup_path = backup / name
        if os.path.lexists(backup_path):
            _remove_path(live_path)
            os.replace(backup_path, live_path)
        elif had_paths.get(name) is not True:
            _remove_path(live_path)


def _recover_interrupted_publication(destination: Path, layout: _CorpusLayout) -> None:
    if not destination.is_dir():
        return
    preparing_prefix = f".{layout.jsonl_name}.preparing."
    for preparing in (
        path for path in destination.iterdir() if path.is_dir() and path.name.startswith(preparing_prefix)
    ):
        shutil.rmtree(preparing)
    prefix = f".{layout.jsonl_name}.backup."
    for backup in sorted(path for path in destination.iterdir() if path.is_dir() and path.name.startswith(prefix)):
        state_path = backup / "state"
        state = state_path.read_text(encoding="utf-8").strip() if state_path.exists() else "publishing"
        if state != "committed":
            _restore_backup(backup, destination, layout)
        shutil.rmtree(backup)


def _publish_snapshot(staging: Path, destination: Path, layout: _CorpusLayout) -> None:
    preparing_prefix = f".{layout.jsonl_name}.preparing."
    backup_prefix = f".{layout.jsonl_name}.backup."
    preparing = Path(tempfile.mkdtemp(dir=destination, prefix=preparing_prefix))
    backup = preparing.with_name(backup_prefix + preparing.name.removeprefix(preparing_prefix))
    publication_names = _publication_names(layout)
    manifest = {"had_paths": {name: os.path.lexists(destination / name) for name in publication_names}}
    try:
        _write_text_atomic(preparing / "transaction.json", json.dumps(manifest, separators=(",", ":")) + "\n")
        _write_text_atomic(preparing / "state", "publishing\n")
        os.replace(preparing, backup)
    except BaseException:
        shutil.rmtree(preparing, ignore_errors=True)
        raise
    try:
        for name in publication_names:
            if manifest["had_paths"][name]:
                os.replace(destination / name, backup / name)
        for name in _generated_names(layout):
            os.replace(staging / name, destination / name)
        _write_text_atomic(backup / "state", "committed\n")
    except BaseException:
        try:
            _restore_backup(backup, destination, layout)
        except BaseException as rollback_error:
            raise RuntimeError(f"snapshot publication failed and backup was preserved at {backup}") from rollback_error
        shutil.rmtree(backup)
        raise
    else:
        shutil.rmtree(backup, ignore_errors=True)


def _normalize_highlight(
    row: JsonObject,
    metadata: JsonObject | None,
    attached_notes: dict[str, list[JsonObject]],
) -> JsonObject | None:
    highlight_id = str(row["id"])
    raw_text = row.get("content")
    if raw_text is not None and not isinstance(raw_text, str):
        raise ValueError(f"Highlight {highlight_id} text was not text")
    text = _text(raw_text)
    if text is None:
        warnings.warn(f"Omitting highlight {highlight_id} because it has no text", UserWarning, stacklevel=2)
        return None
    note = _text(row.get("notes")) or _latest_note(attached_notes.get(highlight_id, []))
    return {
        "id": highlight_id,
        "text": text,
        "note": note,
        "tags": _tags(row.get("tags")),
        "created_at": row.get("created_at") or (metadata or {}).get("created_at"),
        "updated_at": row.get("updated_at") or (metadata or {}).get("updated_at"),
        "reader_url": row.get("url") or (metadata or {}).get("url"),
    }


def _normalize_document(
    metadata: JsonObject,
    details: JsonObject,
    highlights: list[JsonObject],
    attached_notes: dict[str, list[JsonObject]],
) -> JsonObject:
    document_id = str(metadata["id"])
    title = _text(details.get("title")) or _text(metadata.get("title")) or "Untitled"
    raw_content = details.get("content")
    if raw_content is not None and not isinstance(raw_content, str):
        raise ValueError(f"Reader document {document_id} ({title}) content was not text")
    content = _text(raw_content)
    if content is None:
        warnings.warn(
            f"Including Reader document {document_id} ({title}) without content", UserWarning, stacklevel=2
        )
        content = ""
    document_note = _text(details.get("notes")) or _text(metadata.get("notes"))
    if not document_note:
        document_note = _latest_note(attached_notes.get(document_id, []))
    normalized_highlights = sorted(
        highlights,
        key=lambda highlight: (str(highlight.get("created_at") or ""), str(highlight["id"])),
    )
    return {
        "schema_version": SCHEMA_VERSION,
        "id": document_id,
        "title": title,
        "author": _text(details.get("author")) or _text(metadata.get("author")),
        "source": metadata.get("source"),
        "source_url": metadata.get("source_url"),
        "reader_url": metadata.get("url"),
        "site_name": metadata.get("site_name"),
        "category": details.get("category") or metadata.get("category"),
        "location": metadata.get("location"),
        "document_tags": _tags(metadata.get("tags")),
        "summary": _text(metadata.get("summary")),
        "document_note": document_note,
        "published_date": metadata.get("published_date"),
        "created_at": metadata.get("created_at"),
        "saved_at": metadata.get("saved_at"),
        "updated_at": metadata.get("updated_at"),
        "word_count": metadata.get("word_count"),
        "reading_time": metadata.get("reading_time"),
        "listening_time": metadata.get("listening_time"),
        "reading_progress": metadata.get("reading_progress"),
        "first_opened_at": metadata.get("first_opened_at"),
        "last_opened_at": metadata.get("last_opened_at"),
        "image_url": metadata.get("image_url"),
        "highlights": normalized_highlights,
        "content": {"format": "markdown", "text": content},
    }


def _write_corpus_snapshot(
    records: list[JsonObject],
    destination: Path,
    layout: _CorpusLayout = MAIN_LAYOUT,
    markdown_directory_by_id: dict[str, str] | None = None,
) -> tuple[Path, tuple[Path, ...]]:
    destination = destination.expanduser().resolve()
    jsonl_path = destination / layout.jsonl_name
    markdown_dirs = tuple(destination / name for name in layout.markdown_directories)
    destination.mkdir(parents=True, exist_ok=True)
    previous_records = _previous_records(jsonl_path)
    if markdown_directory_by_id is None:
        if len(layout.markdown_directories) != 1:
            raise ValueError("a Markdown directory is required for each record")
        markdown_directory_by_id = {str(record["id"]): layout.markdown_directories[0] for record in records}
    for markdown_directory in layout.markdown_directories:
        directory_records = [
            record
            for record in records
            if markdown_directory_by_id.get(str(record["id"])) == markdown_directory
        ]
        _assign_markdown_paths(
            directory_records,
            destination,
            previous_records,
            markdown_directory,
            preserve_unmanaged_files=layout.preserve_unmanaged_files,
        )
    if any("markdown_path" not in record for record in records):
        raise ValueError("every record must belong to a Markdown directory")

    rendered_markdown = [(str(record["markdown_path"]), _markdown(record)) for record in records]
    jsonl = "".join(json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n" for record in records)
    staging = Path(tempfile.mkdtemp(dir=destination, prefix=f".{layout.jsonl_name}.staging."))
    try:
        for markdown_directory in layout.markdown_directories:
            staged_markdown_dir = staging / markdown_directory
            staged_markdown_dir.mkdir()
            if layout.preserve_unmanaged_files:
                _copy_unmanaged_entries(
                    destination / markdown_directory,
                    staged_markdown_dir,
                    previous_records,
                    markdown_directory,
                )
        for relative_path, content in rendered_markdown:
            _write_text_atomic(staging / relative_path, content)
        _write_text_atomic(staging / layout.jsonl_name, jsonl)
        _publish_snapshot(staging, destination, layout)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return jsonl_path, markdown_dirs


def _build_corpus(
    source: ReaderSource,
    destination: Path,
    *,
    layout: _CorpusLayout,
    backfill_only: bool,
    workers: int = 4,
    progress: Callable[[int, int, str], None] | None = None,
) -> BuildResult:
    metadata_records = source.list_records()
    highlight_records = source.list_records(category="highlight", include_content=True)
    note_records = source.list_records(category="note", include_content=True)
    _validate_unique_ids(metadata_records, "document")
    _validate_unique_ids(highlight_records, "highlight")
    _validate_unique_ids(note_records, "note")

    eligible_metadata: list[JsonObject] = []
    excluded_backfill = 0
    for record in metadata_records:
        location = _text(record.get("location"))
        is_child = record.get("parent_id") is not None
        is_feed = bool(location and location.casefold() == "feed")
        if is_child or is_feed or record.get("is_deleted") is True:
            continue
        record_tags = _tags(record.get("tags"))
        is_backfill = any(_is_backfill(tag) for tag in record_tags)
        if backfill_only:
            if is_backfill:
                eligible_metadata.append(record)
            continue
        if is_backfill:
            excluded_backfill += 1
            continue
        eligible_metadata.append(record)

    eligible_ids = {str(record["id"]) for record in eligible_metadata}
    metadata_by_id = {str(record["id"]): record for record in metadata_records}
    interaction_ids = {
        str(record["id"])
        for record in eligible_metadata
        if _tags(record.get("tags")) or _text(record.get("notes"))
    }
    attached_notes: dict[str, list[JsonObject]] = defaultdict(list)
    active_notes: list[JsonObject] = []
    for note in note_records:
        if note.get("parent_id") and note.get("is_deleted") is not True:
            attached_notes[str(note["parent_id"])].append(note)
            active_notes.append(note)

    highlights_by_document: dict[str, list[JsonObject]] = defaultdict(list)
    active_highlight_parents: dict[str, str] = {}
    omitted_highlights = 0
    for highlight in highlight_records:
        parent_id = str(highlight.get("parent_id") or "")
        if parent_id not in eligible_ids or highlight.get("is_deleted") is True:
            continue
        highlight_id = str(highlight["id"])
        interaction_ids.add(parent_id)
        active_highlight_parents[highlight_id] = parent_id
        normalized = _normalize_highlight(highlight, metadata_by_id.get(highlight_id), attached_notes)
        if normalized is None:
            omitted_highlights += 1
            continue
        highlights_by_document[parent_id].append(normalized)

    for note in active_notes:
        parent_id = str(note["parent_id"])
        if parent_id in eligible_ids:
            interaction_ids.add(parent_id)
        elif parent_id in active_highlight_parents:
            interaction_ids.add(active_highlight_parents[parent_id])

    details_by_id: dict[str, JsonObject] = {}
    total = len(eligible_metadata)
    with ThreadPoolExecutor(max_workers=max(1, workers)) as executor:
        futures = {
            executor.submit(source.get_document_details, str(metadata["id"])): metadata
            for metadata in eligible_metadata
        }
        completed = 0
        for future in as_completed(futures):
            metadata = futures[future]
            details_by_id[str(metadata["id"])] = future.result()
            completed += 1
            if progress:
                progress(completed, total, _text(metadata.get("title")) or "Untitled")

    records = [
        _normalize_document(
            metadata,
            details_by_id[str(metadata["id"])],
            highlights_by_document.get(str(metadata["id"]), []),
            attached_notes,
        )
        for metadata in eligible_metadata
    ]
    records.sort(key=lambda record: record["id"])

    documents_with_interactions = 0
    documents_without_interactions = 0
    markdown_directory_by_id: dict[str, str] | None = None
    if not backfill_only:
        for metadata in eligible_metadata:
            document_id = str(metadata["id"])
            details = details_by_id[document_id]
            if _tags(details.get("tags")) or _text(details.get("notes")):
                interaction_ids.add(document_id)
        documents_with_interactions = len(interaction_ids)
        documents_without_interactions = len(records) - documents_with_interactions
        markdown_directory_by_id = {
            str(record["id"]): (
                WITH_INTERACTIONS_DIRECTORY
                if str(record["id"]) in interaction_ids
                else WITHOUT_INTERACTIONS_DIRECTORY
            )
            for record in records
        }

    jsonl_path, markdown_dirs = _write_corpus_snapshot(
        records,
        destination,
        layout,
        markdown_directory_by_id,
    )

    return BuildResult(
        documents=len(records),
        documents_without_content=sum(not record["content"]["text"] for record in records),
        documents_with_interactions=documents_with_interactions,
        documents_without_interactions=documents_without_interactions,
        highlights=sum(len(record["highlights"]) for record in records),
        omitted_highlights=omitted_highlights,
        excluded_backfill=excluded_backfill,
        jsonl_path=jsonl_path,
        markdown_dirs=markdown_dirs,
    )


def build_corpus(
    source: ReaderSource,
    destination: Path,
    *,
    workers: int = 4,
    progress: Callable[[int, int, str], None] | None = None,
) -> BuildResult:
    """Build the replaceable main corpus snapshot from Reader."""
    destination = destination.expanduser().resolve()
    _recover_interrupted_publication(destination, MAIN_LAYOUT)
    return _build_corpus(
        source,
        destination,
        layout=MAIN_LAYOUT,
        backfill_only=False,
        workers=workers,
        progress=progress,
    )


def build_backfill_corpus(
    source: ReaderSource,
    destination: Path,
    *,
    workers: int = 4,
    progress: Callable[[int, int, str], None] | None = None,
) -> BuildResult:
    """Build the static backfill snapshot once and refuse to replace it."""
    destination = destination.expanduser().resolve()
    _recover_interrupted_publication(destination, BACKFILL_LAYOUT)
    jsonl_path = destination / BACKFILL_LAYOUT.jsonl_name
    if os.path.lexists(jsonl_path):
        raise FileExistsError(f"static backfill snapshot already exists at {destination}")
    return _build_corpus(
        source,
        destination,
        layout=BACKFILL_LAYOUT,
        backfill_only=True,
        workers=workers,
        progress=progress,
    )
